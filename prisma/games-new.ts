/** Лабиринтті суретпен жазу: S — робот, G — жұлдыз, # — бұта, . — жол. dir: 0 ↑, 1 →, 2 ↓, 3 ←. */
function maze(rows: string[], dir: number, limit?: number) {
  const h = rows.length, w = rows[0].length, walls: number[] = [];
  let start = 0, goal = 0;
  rows.forEach((r, y) => r.split("").forEach((c, x) => {
    const i = y * w + x;
    if (c === "#") walls.push(i);
    if (c === "S") start = i;
    if (c === "G") goal = i;
  }));
  return { w, h, walls, start, dir, goal, ...(limit ? { limit } : {}) };
}
